#!/usr/bin/env python3
"""Turn "name address" lists into absolute symbol definitions (fe8 port).

The native build reads game data in place from the player's ROM, which the
port maps at the GBA cartridge address (0x08000000), and keeps the GBA's RAM
regions at their hardware addresses too. Symbols that live there on the GBA
are defined as absolute symbols at the same address, so the game code links
against them unchanged.

Usage: gen_abs_symbols.py OUT.S LIST [LIST...]

Names listed in port/data/native_symbols.txt are skipped: the port defines
those natively.
"""
from pathlib import Path
import sys


def main():
    out, lists = sys.argv[1], sys.argv[2:]
    lines = ["/* Generated by tools/port/gen_abs_symbols.py: do not edit. */\n"]
    native = Path(__file__).resolve().parents[2] / "port/data/native_symbols.txt"
    seen = {l.split("#", 1)[0].strip() for l in native.read_text().splitlines()} - {""}
    for path in lists:
        for row in open(path):
            row = row.split("#", 1)[0].split()
            if not row:
                continue
            name, addr = row[0], int(row[1], 16)
            if name in seen:
                continue
            seen.add(name)
            # Hidden: resolved at link time, with no dynamic relocation (the
            # address is the same in every process).
            lines.append(f"\t.globl {name}\n\t.hidden {name}\n\t.set {name}, 0x{addr:08x}\n")
    text = "".join(lines)
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    with open(out, "w") as f:
        f.write(text)


if __name__ == "__main__":
    main()
