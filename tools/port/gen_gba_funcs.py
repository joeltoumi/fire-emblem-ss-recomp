#!/usr/bin/env python3
"""Generate the GBA address -> native function table (fe8 port).

ROM data (event scripts, event lists...) holds GBA addresses of game
functions. Port_GbaFunc() looks them up in this table, generated from
port/data/rom_funcs_<region>.txt (see tools/port/gen_rom_funcs.py).

Usage: gen_gba_funcs.py OUT.c LIST
"""
import sys


def main():
    out, path = sys.argv[1], sys.argv[2]
    rows = sorted((int(a, 16), n) for n, a in (l.split() for l in open(path) if l.strip()))
    lines = ["// Generated by tools/port/gen_gba_funcs.py: do not edit.\n\n",
             '#include "global.h"\n#include "port/platform.h"\n\n']
    lines += [f"void {n}(void);\n" for n in sorted({n for _, n in rows})]
    lines.append("\nstatic const struct { u32 addr; void (*func)(void); } sGbaFuncs[] = {\n")
    lines += [f"    {{ 0x{a:08x}, {n} }},\n" for a, n in rows]
    lines.append("};\n\n")
    lines.append("""void *Port_GbaFunc(u32 addr)
{
    int lo = 0, hi = ARRAY_COUNT(sGbaFuncs);

    addr &= ~1u;
    while (lo < hi)
    {
        int mid = (lo + hi) / 2;
        if (sGbaFuncs[mid].addr == addr)
            return (void *)sGbaFuncs[mid].func;
        if (sGbaFuncs[mid].addr < addr)
            lo = mid + 1;
        else
            hi = mid;
    }
    Port_Log("no native function for GBA address %08x", (unsigned)addr);
    return NULL;
}
""")
    text = "".join(lines)
    try:
        if open(out).read() == text:
            return
    except OSError:
        pass
    open(out, "w").write(text)


if __name__ == "__main__":
    main()
