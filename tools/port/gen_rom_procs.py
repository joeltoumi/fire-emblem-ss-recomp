#!/usr/bin/env python3
"""Turn the proc scripts written as assembly data into C (fe8 port).

A few proc scripts are still assembly in data/*.s. They hold pointers to
game functions, so the port can't read them in place from the ROM like the
rest of the data: they are generated as native ProcCmd arrays in
port/game/rom_procs.c, and their names are listed in
port/data/native_symbols.txt so they are not taken from the ROM.

Usage: gen_rom_procs.py ELF
(ELF: the GBA build, to tell functions from data.)
"""
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]

# (file, label) of each proc script in assembly data.
SCRIPTS = [
    ("data/data-ekrdragon.s", "ProcScr_EkrDragon_08758720"),
    ("data/data_9A31F8.s", "ProcScr_ManimShiftingSineWaveScanlineBuf"),
    ("data/data_AA6BFA.s", "gUnknown_08AA704C"),
    ("data/data_AA6BFA.s", "gUnknown_08AA705C"),
    ("data/data_AA6BFA.s", "gUnknown_08AA707C"),
    ("data/opanim.s", "ProcScr_OpAnim"),
]


def parse(path, label):
    lines = (ROOT / path).read_text().splitlines()
    start = next(i for i, l in enumerate(lines) if re.match(rf"\s*{label}:", l))
    cmds = []
    pending = None
    for l in lines[start + 1:]:
        s = l.split("@")[0].strip()
        if not s:
            continue
        m = re.match(r"\.short\s+(\S+),\s*(\S+)$", s)
        if m and pending is None:
            pending = (int(m.group(1), 0), int(m.group(2), 0))
            continue
        m = re.match(r"\.word\s+(\S+)$", s)
        if m and pending is not None:
            cmds.append((*pending, m.group(1)))
            pending = None
            continue
        break
    if pending is not None or not cmds or cmds[-1][0] != 0:
        sys.exit(f"{path}: {label}: not a proc script ending in PROC_END")
    return cmds


def main():
    out = subprocess.run(["arm-none-eabi-readelf", "-sW", sys.argv[1]], check=True, capture_output=True, text=True).stdout
    kinds = {p[7]: p[3] for p in (l.split() for l in out.splitlines()) if len(p) == 8}
    scripts = [(label, parse(path, label)) for path, label in SCRIPTS]
    labels = {label for label, _ in scripts}
    funcs, data = set(), set()
    for _, cmds in scripts:
        for _, _, ptr in cmds:
            if re.match(r"0x[0-9a-fA-F]+$|\d+$", ptr) or ptr in labels:
                continue
            (funcs if kinds.get(ptr) == "FUNC" else data).add(ptr)

    with (ROOT / "port/game/rom_procs.c").open("w") as f:
        f.write("// Generated by tools/port/gen_rom_procs.py: do not edit.\n//\n")
        f.write("// Proc scripts that are assembly data in the decomp (they point to game\n")
        f.write("// functions, so they can't be read from the ROM).\n\n")
        f.write('#include "global.h"\n#include "proc.h"\n\n')
        for n in sorted(funcs):
            f.write(f"void {n}();\n")
        for n in sorted(data):
            f.write(f"extern const u8 {n}[];\n")
        for label, _ in scripts:
            f.write(f"extern const struct ProcCmd {label}[];\n")
        for label, cmds in scripts:
            f.write(f"\nconst struct ProcCmd {label}[] = {{\n")
            for op, imm, ptr in cmds:
                p = "0" if ptr in ("0", "0x0") else (f"(const void *){ptr}" if not ptr[0].isdigit() else f"(const void *)(uintptr_t){ptr}")
                f.write(f"    {{ 0x{op:02x}, 0x{imm & 0xFFFF:04x}, {p} }},\n")
            f.write("};\n")
    with (ROOT / "port/data/native_symbols.txt").open("w") as f:
        f.write("# ROM symbols the port defines natively (not read from the ROM).\n")
        for label, _ in scripts:
            f.write(f"{label}\n")


if __name__ == "__main__":
    main()
